#!/usr/bin/env bash
# ---------------------------------------------------------------------------
# FILE: scripts/test-doctor-resolv-conf.sh
# PURPOSE (plain English):
#   Proves doctor.sh's /etc/resolv.conf ownership check by RUNNING doctor.sh
#   against stubbed tailscale/docker/systemctl and fixture resolv.conf files --
#   it does not merely grep the text of doctor.sh.
#
#   On the Pi, tailscaled writes /etc/resolv.conf itself (direct-file mode),
#   because the host runs neither systemd-resolved nor resolvconf. Its own
#   health line "System DNS config not ideal. /etc/resolv.conf overwritten." is
#   that mode announcing itself: expected and benign. doctor.sh must say so
#   without moving its exit code, and must warn only if the file turns out not
#   to be tailscaled-generated.
#
#   Fully OFFLINE. No Docker, no network, no root, no real /etc/resolv.conf.
#   The file under inspection is named through doctor.sh's internal
#   DOCTOR_RESOLV_CONF seam, so the check is driven with fixture files.
#
#   Proven here:
#     (a) expected state -- health line present AND tailscaled header present ->
#         an informational note, no warn, no fail, and every summary count and
#         the exit code identical to a baseline run of the same doctor.sh with
#         the check removed;
#     (b) foreign owner -- health line present, tailscaled header absent -> a
#         warn naming the changed ownership, exit 1 (never 2), and exactly one
#         extra warning over the baseline;
#     (c) tailscale unreachable (status exits non-zero) and the tailscale CLI
#         absent -> a skip line, no informational note from this check, and no
#         warn or fail attributed to it (counts identical to the baseline);
#     (d) cleanliness -- the fixture's nameserver literal and the body of the
#         fixture file never reach the report: only the header is matched.
#
#   The baseline is a copy of the doctor.sh under test with the 6a section
#   removed, so "unchanged" compares like with like. If the doctor.sh under
#   test has no such section (the unpatched base), this harness fails at once:
#   assertion (a) could not print the note, so the harness genuinely tests the
#   new behaviour.
#
# Usage:
#   bash scripts/test-doctor-resolv-conf.sh [path-to-doctor.sh]
#
# The path defaults to doctor.sh at the repository root, resolved from this
# script's own location so the harness runs from anywhere. Point it at a copy
# of the base doctor.sh to see it fail.
# Exit 0 when every assertion passes, 1 on assertion failure, 2 on usage error.
# ---------------------------------------------------------------------------
set -uo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd -- "${SCRIPT_DIR}/.." && pwd)"

DOCTOR="${1:-$REPO_ROOT/doctor.sh}"
if [[ ! -f "$DOCTOR" ]]; then
  echo "FAIL: doctor.sh not found: $DOCTOR" >&2
  exit 2
fi

for t in mktemp timeout git jq; do
  command -v "$t" >/dev/null 2>&1 || { echo "FAIL: ${t} is required" >&2; exit 2; }
done

WORK="$(mktemp -d)"
if [[ -n "${RC_KEEP:-}" ]]; then
  trap 'echo "kept: $WORK" >&2' EXIT
else
  trap 'rm -rf -- "$WORK"' EXIT
fi

PASS=0
FAILURES=0
pass() { PASS=$((PASS + 1)); echo "PASS: $1"; }
fail() { echo "FAIL: $1" >&2; FAILURES=$((FAILURES + 1)); }

BIN="$WORK/bin"
FIXDIR="$WORK/fixtures"
APPD="$WORK/app"
mkdir -p "$BIN" "$FIXDIR" "$APPD/scripts/lib" "$WORK/home" "$WORK/ws" "$WORK/ohstate"

NOTE_RE='tailscaled owns .* in direct-file mode'
SKIP_RE='resolv.conf ownership check skipped'
WARN_RE='does NOT carry the tailscaled header'
TS_HEADER='# resolv.conf(5) file generated by tailscale'
# The literal that must never appear in the report. It is a fixture value, not
# a real address from any host.
FIXTURE_NS='nameserver 192.0.2.53'
FIXTURE_NS_ADDR='192.0.2.53'

# --- stubs ------------------------------------------------------------------
# docker: answers just enough that doctor's container, binding and sandbox
# checks pass, so they never move the exit code.
cat > "$BIN/docker" <<'EOF'
#!/usr/bin/env bash
for a in "$@"; do [[ "$a" == "info" ]] && exit 0; done
tmpl=""; prev=""
for a in "$@"; do
  [[ "$prev" == "-f" ]] && tmpl="$a"
  prev="$a"
done
for a in "$@"; do [[ "$a" == "network" ]] && exit 1; done
[[ "$*" == *"hermes-agent"* ]] && exit 1
[[ "$*" == *"name=oh-agent-server"* ]] && exit 0
case "$tmpl" in
  *".State.Status"*) echo running; exit 0 ;;
  *".State.Health"*) echo none; exit 0 ;;
  *"RestartCount"*)  echo 0; exit 0 ;;
  *"PortBindings"*)  echo '172.17.0.1:3001 '; exit 0 ;;
  *"println ."*)
    printf '%s\n' \
      'AGENT_SERVER_IMAGE_REPOSITORY=ghcr.io/jimbobsyouruncle/openhands-agent-server-hybrid' \
      'AGENT_SERVER_IMAGE_TAG=1.37.1-python-hybrid.3' \
      'SANDBOX_HOST_PORT=3001' \
      'SANDBOX_CONTAINER_URL_PATTERN=http://example.test:{port}' \
      'OH_PERMITTED_CORS_ORIGINS_0=http://localhost:3001' \
      'OH_PERMITTED_CORS_ORIGINS_1=http://172.17.0.1:3001'
    exit 0 ;;
esac
exit 1
EOF

cat > "$BIN/getfacl" <<'EOF'
#!/usr/bin/env bash
printf 'user:10001:rwx\ndefault:user:10001:rwx\n'
exit 0
EOF

cat > "$BIN/sleep" <<'EOF'
#!/usr/bin/env bash
exit 0
EOF

cat > "$BIN/restic" <<'EOF'
#!/usr/bin/env bash
exit 1
EOF

# --- host probes ------------------------------------------------------------
# doctor.sh inspects the REAL host (disk, boot device, RAM, kernel log). Pin
# each probe so the ONLY thing that can move the exit code is the fixture.
cat > "$BIN/df" <<'EOF'
#!/usr/bin/env bash
printf 'Use%%\n 41%%\n'
EOF

cat > "$BIN/findmnt" <<'EOF'
#!/usr/bin/env bash
echo '/dev/nvme0n1p2'
EOF

cat > "$BIN/nvme" <<'EOF'
#!/usr/bin/env bash
exit 1
EOF

cat > "$BIN/lsblk" <<'EOF'
#!/usr/bin/env bash
exit 1
EOF

cat > "$BIN/dmesg" <<'EOF'
#!/usr/bin/env bash
exit 0
EOF

cat > "$BIN/vcgencmd" <<'EOF'
#!/usr/bin/env bash
exit 1
EOF

cat > "$BIN/hostname" <<'EOF'
#!/usr/bin/env bash
for a in "$@"; do
  case "$a" in
    -I) echo '10.0.0.5 '; exit 0 ;;
  esac
done
echo 'hybrid-ai-test-host'
EOF

# The pod's MagicDNS name resolves through the shared resolver's fallback.
cat > "$BIN/getent" <<'EOF'
#!/usr/bin/env bash
case "${1:-}" in
  ahostsv4)
    case "${2:-}" in
      runpod-worker.example.test) echo '100.64.0.9  STREAM'; exit 0 ;;
    esac ;;
esac
exit 2
EOF

cat > "$BIN/systemctl" <<'EOF'
#!/usr/bin/env bash
exit 1
EOF

cat > "$BIN/journalctl" <<'EOF'
#!/usr/bin/env bash
exit 0
EOF

cat > "$BIN/ip" <<'EOF'
#!/usr/bin/env bash
exit 0
EOF

cat > "$BIN/uname" <<'EOF'
#!/usr/bin/env bash
for a in "$@"; do
  case "$a" in
    -m) echo 'aarch64'; exit 0 ;;
  esac
done
echo 'Linux'
EOF

cat > "$BIN/nproc" <<'EOF'
#!/usr/bin/env bash
echo 4
EOF

for t in sqlite3 rsync; do
  cat > "$BIN/$t" <<'EOF'
#!/usr/bin/env bash
exit 0
EOF
done

# tailscale: connected with no GPU pod peer (a pass plus a stable warning, never
# a failure). TS_MODE decides what the Health array carries and whether the
# daemon answers at all:
#   warn        -> the real "System DNS config not ideal" health line
#   clean       -> no health lines at all
#   unreachable -> `status --json` exits non-zero, as a stopped daemon does
cat > "$BIN/tailscale" <<'EOF'
#!/usr/bin/env bash
sub=""
for a in "$@"; do
  case "$a" in
    -*) continue ;;
    *) sub="$a"; break ;;
  esac
done
case "$sub" in
  status)
    case "${TS_MODE:-warn}" in
      unreachable) echo 'failed to connect to local tailscaled' >&2; exit 1 ;;
      clean) echo '{"BackendState":"Running","Health":[],"Peer":{}}'; exit 0 ;;
      *)
        echo '{"BackendState":"Running","Health":["System DNS config not ideal. /etc/resolv.conf overwritten."],"Peer":{}}'
        exit 0 ;;
    esac ;;
  ip)
    case "${*: -1}" in
      runpod-worker.example.test) echo '100.64.0.9'; exit 0 ;;
    esac
    exit 1 ;;
esac
exit 0
EOF

# curl: local health endpoints answer so the Services checks pass; everything
# else fails, as a host with nothing else running would.
cat > "$BIN/curl" <<'EOF'
#!/usr/bin/env bash
url="${*: -1}"
case "$url" in
  *":11434/api/tags") printf '%s' '{"models":[{"name":"llama3.2:3b"}]}'; exit 0 ;;
  *":3000/health") exit 0 ;;
  *":3001/"*) exit 0 ;;
esac
exit 7
EOF

chmod +x "$BIN"/*

# doctor.sh runs under `set -o pipefail`, and several checks read a stub through
# `... | grep -q`. grep -q exits at the first match, so the stub can be killed
# by SIGPIPE (exit 141) before it finishes writing; pipefail then reports the
# whole pipeline as failed and flips an unrelated check. That race is a property
# of the stub, not of doctor.sh, so every stub ignores SIGPIPE.
for f in "$BIN"/*; do
  [[ "$(head -n1 "$f")" == '#!/usr/bin/env bash' ]] && sed -i "2i trap '' PIPE" "$f"
done

# --- fixtures ---------------------------------------------------------------
# (1) the documented state: tailscaled's own header, then its nameservers.
RESOLV_TS="$FIXDIR/resolv.tailscale"
{
  printf '%s\n' "$TS_HEADER"
  printf '%s\n' '# For more info, see https://tailscale.com/s/resolvconf-overwrite'
  printf '%s\n' '# DO NOT EDIT THIS FILE BY HAND -- CHANGES WILL BE OVERWRITTEN'
  printf '%s\n' "$FIXTURE_NS"
  printf '%s\n' 'nameserver fd7a:115c:a1e0::53'
  printf '%s\n' 'search example-tailnet.ts.net lan'
} > "$RESOLV_TS"

# (2) foreign owner: a resolv.conf some other manager wrote. No tailscale header.
RESOLV_FOREIGN="$FIXDIR/resolv.foreign"
{
  printf '%s\n' '# Generated by NetworkManager'
  printf '%s\n' "$FIXTURE_NS"
} > "$RESOLV_FOREIGN"

# --- scratch app ------------------------------------------------------------
cp "$REPO_ROOT/scripts/lib/hybrid-ai-env.sh" "$APPD/scripts/lib/"
# doctor.sh resolves the pod MagicDNS name through this shared lib.
cp "$REPO_ROOT/scripts/lib/tailscale-resolve.sh" "$APPD/scripts/lib/"
cp "$DOCTOR" "$APPD/doctor.sh"
chmod +x "$APPD/doctor.sh"

# The baseline: the same doctor.sh with the 6a section deleted. Comparing
# against this, rather than against a run of the patched file, is what makes
# "the exit code is unchanged" a real statement.
awk '/^# 6a\. \/etc\/resolv\.conf ownership/ {skip=1}
     /^# 7\. Backups/ {skip=0}
     !skip' "$APPD/doctor.sh" > "$APPD/doctor-base.sh"
chmod +x "$APPD/doctor-base.sh"

# If the doctor.sh under test lacks the section, say so and keep going: the
# assertions below then fail on their own evidence (no note, no skip line, no
# extra warn), which is what proves this harness tests the new behaviour rather
# than merely matching text.
if ! grep -qF 'resolv_skip()' "$APPD/doctor.sh"; then
  :
  fail "the doctor.sh under test has no resolv.conf ownership check (unpatched base)"
fi
if grep -qF 'resolv_skip()' "$APPD/doctor-base.sh"; then
  fail "could not build the baseline: the 6a section was not removed"
fi

( cd "$WORK/ws" && git init -q && touch .keep ) >/dev/null 2>&1
chmod 700 "$WORK/ohstate"

cat > "$APPD/.env" <<EOF
WEBUI_SECRET_KEY=fixture
RUNPOD_API_KEY=fixture
RUNPOD_POD_ID=fixture
RUNPOD_HOST=runpod-worker.example.test
PEER_HOSTNAME=fixture
OPENROUTER_API_KEY=fixture
OPENHANDS_WORKSPACE=$WORK/ws
OPENHANDS_SANDBOX_HOST=example.test
OPENHANDS_STATE_DIR=$WORK/ohstate
EOF
chmod 600 "$APPD/.env"

count_of() { # file key -> number from the summary line
  case "$2" in
    passed)       sed -n 's/^ *\([0-9]\+\) passed.*/\1/p' "$1" | tail -1 ;;
    'warning(s)') sed -n 's/^.* \([0-9]\+\) warning(s).*/\1/p' "$1" | tail -1 ;;
    'failure(s)') sed -n 's/^.* \([0-9]\+\) failure(s).*/\1/p' "$1" | tail -1 ;;
  esac
}

run_doctor() { # name doctor-path resolv-path mode [path-override] ; sets RC
  local name="$1" doc="$2" resolv="$3" mode="$4" runpath="${5:-$BIN:$PATH}"
  (
    cd "$APPD" || exit 1
    env TS_MODE="$mode" DOCTOR_RESOLV_CONF="$resolv" \
      PATH="$runpath" HOME="$WORK/home" SHELL=/bin/bash \
      HYBRID_AI_DATA_DIR="$APPD" HYBRID_AI_LOG_DIR="$APPD" HYBRID_AI_WORK_DIR="$APPD" \
      timeout 120 bash "$doc" --no-cloud
  ) > "$WORK/out.$name" 2>&1
  RC=$?
}

# --- baseline: same doctor.sh, no check ------------------------------------
run_doctor base "$APPD/doctor-base.sh" "$RESOLV_TS" warn
RC_BASE=$RC
BASE_PASS="$(count_of "$WORK/out.base" passed)"
BASE_WARN="$(count_of "$WORK/out.base" 'warning(s)')"
BASE_FAIL="$(count_of "$WORK/out.base" 'failure(s)')"
if [[ -n "$BASE_PASS" && -n "$BASE_WARN" && -n "$BASE_FAIL" ]]; then
  pass "baseline runs and reports counts (${BASE_PASS} passed, ${BASE_WARN} warning(s), ${BASE_FAIL} failure(s), exit ${RC_BASE})"
else
  fail "baseline summary line is unreadable"
fi
if ! grep -q "$NOTE_RE" "$WORK/out.base"; then
  pass "baseline (check removed) prints no resolv.conf ownership note"
else
  fail "baseline unexpectedly printed the resolv.conf ownership note"
fi

# --- (a) expected state -> informational note, nothing else ----------------
run_doctor expected "$APPD/doctor.sh" "$RESOLV_TS" warn
RC_EXPECTED=$RC
OUT_EXPECTED="$WORK/out.expected"
if grep -q "$NOTE_RE" "$OUT_EXPECTED"; then
  pass "expected state: an informational note says tailscaled owns the file in direct-file mode"
else
  fail "expected state: no informational note about direct-file mode"
fi
if grep -q 'System DNS config not ideal' "$OUT_EXPECTED" \
   && grep -q 'tailscale.com/s/dns-fight' "$OUT_EXPECTED"; then
  pass "expected state: the note quotes the health line and links the upstream explanation"
else
  fail "expected state: the note does not quote the health line with the dns-fight link"
fi
if grep -q "$WARN_RE" "$OUT_EXPECTED"; then
  fail "expected state: the check warned about a foreign owner when the header is present"
else
  pass "expected state: no warn about a foreign owner"
fi
if [[ "$(count_of "$OUT_EXPECTED" passed)" == "$BASE_PASS" \
      && "$(count_of "$OUT_EXPECTED" 'warning(s)')" == "$BASE_WARN" \
      && "$(count_of "$OUT_EXPECTED" 'failure(s)')" == "$BASE_FAIL" ]]; then
  pass "expected state: every summary count equals the baseline (the note moves no counter)"
else
  fail "expected state: summary counts moved off the baseline ($(count_of "$OUT_EXPECTED" passed)/$(count_of "$OUT_EXPECTED" 'warning(s)')/$(count_of "$OUT_EXPECTED" 'failure(s)') vs ${BASE_PASS}/${BASE_WARN}/${BASE_FAIL})"
fi
if [[ "$RC_EXPECTED" == "$RC_BASE" ]]; then
  pass "expected state: exit code is unaffected by the note (${RC_EXPECTED})"
else
  fail "expected state: exit code ${RC_EXPECTED} differs from the baseline (${RC_BASE})"
fi

# --- (b) foreign owner -> warn (exit 1 at worst), never fail --------------
run_doctor foreign "$APPD/doctor.sh" "$RESOLV_FOREIGN" warn
RC_FOREIGN=$RC
OUT_FOREIGN="$WORK/out.foreign"
if grep -q "$WARN_RE" "$OUT_FOREIGN"; then
  pass "foreign owner: a warn says the file no longer carries the tailscaled header"
else
  fail "foreign owner: no warn about the changed ownership"
fi
if grep -q 'docs/TROUBLESHOOTING.md' "$OUT_FOREIGN"; then
  pass "foreign owner: the remedy points at the troubleshooting section"
else
  fail "foreign owner: the remedy does not point at docs/TROUBLESHOOTING.md"
fi
if [[ "$RC_FOREIGN" != "2" ]]; then
  pass "foreign owner: the exit code is never 2 (got ${RC_FOREIGN})"
else
  fail "foreign owner: exit code is 2 -- a changed owner must never be a failure"
fi
if [[ "$RC_FOREIGN" == "1" ]]; then
  pass "foreign owner: the exit code is 1 (warnings only)"
else
  fail "foreign owner: exit code is ${RC_FOREIGN}, expected 1"
fi
if [[ "$(count_of "$OUT_FOREIGN" 'warning(s)')" == "$(( BASE_WARN + 1 ))" \
      && "$(count_of "$OUT_FOREIGN" 'failure(s)')" == "$BASE_FAIL" ]]; then
  pass "foreign owner: exactly one extra warning over the baseline and no extra failure"
else
  fail "foreign owner: expected $(( BASE_WARN + 1 )) warning(s) and ${BASE_FAIL} failure(s), got $(count_of "$OUT_FOREIGN" 'warning(s)')/$(count_of "$OUT_FOREIGN" 'failure(s)')"
fi
if ! grep -q "$NOTE_RE" "$OUT_FOREIGN"; then
  pass "foreign owner: the informational note is not printed (the state is not the expected one)"
else
  fail "foreign owner: the expected-state note was printed for a foreign owner"
fi

# --- (c) unreachable daemon and absent CLI -> skip, add nothing -----------
# The stub daemon not answering also trips doctor's EXISTING "Tailscale backend
# state" failure, so this case is compared against the baseline rather than
# against exit 0: the point is that the NEW check contributes no warn and no
# fail of its own.
run_doctor unreachable "$APPD/doctor.sh" "$RESOLV_TS" unreachable
RC_UNREACH=$RC
OUT_UNREACH="$WORK/out.unreachable"
run_doctor unreachable-base "$APPD/doctor-base.sh" "$RESOLV_TS" unreachable
RC_UNREACH_BASE=$RC
if grep -q "$SKIP_RE" "$OUT_UNREACH"; then
  pass "unreachable daemon: a skip line is printed"
else
  fail "unreachable daemon: no skip line"
fi
if ! grep -q "$NOTE_RE" "$OUT_UNREACH" && ! grep -q "$WARN_RE" "$OUT_UNREACH"; then
  pass "unreachable daemon: no informational note and no warn from this check"
else
  fail "unreachable daemon: the check printed a note or a warn it could not justify"
fi
if [[ "$(count_of "$OUT_UNREACH" 'warning(s)')" == "$(count_of "$WORK/out.unreachable-base" 'warning(s)')" \
      && "$(count_of "$OUT_UNREACH" 'failure(s)')" == "$(count_of "$WORK/out.unreachable-base" 'failure(s)')" \
      && "$RC_UNREACH" == "$RC_UNREACH_BASE" ]]; then
  pass "unreachable daemon: counts and exit code equal the check-free baseline (${RC_UNREACH_BASE})"
else
  fail "unreachable daemon: the check moved counts or the exit code off the baseline"
fi

# A PATH with no tailscale at all: `command -v tailscale` must genuinely fail,
# so omitting the binary is the only honest way to prove the skip path.
NOTS_BIN="$WORK/bin-notailscale"
mkdir -p "$NOTS_BIN"
for f in "$BIN"/*; do
  n="$(basename "$f")"
  [[ "$n" == "tailscale" ]] && continue
  ln -sf "$f" "$NOTS_BIN/$n"
done
IFS=: read -r -a _path_dirs <<< "$PATH"
for d in "${_path_dirs[@]}"; do
  [[ -d "$d" ]] || continue
  for f in "$d"/*; do
    n="$(basename "$f")"
    [[ "$n" == "tailscale" ]] && continue
    [[ -x "$f" && ! -e "$NOTS_BIN/$n" ]] && ln -s "$f" "$NOTS_BIN/$n" 2>/dev/null
  done
done
unset _path_dirs d f n
command -v jq >/dev/null 2>&1 && ln -sf "$(command -v jq)" "$NOTS_BIN/jq"

run_doctor nots "$APPD/doctor.sh" "$RESOLV_TS" warn "$NOTS_BIN"
RC_NOTS=$RC
OUT_NOTS="$WORK/out.nots"
run_doctor nots-base "$APPD/doctor-base.sh" "$RESOLV_TS" warn "$NOTS_BIN"
RC_NOTS_BASE=$RC
if grep -q "${SKIP_RE} (tailscale CLI is not installed)" "$OUT_NOTS"; then
  pass "tailscale absent: the skip line says the CLI is not installed"
else
  fail "tailscale absent: no skip line naming the missing CLI"
fi
if ! grep -q "$NOTE_RE" "$OUT_NOTS" && ! grep -q "$WARN_RE" "$OUT_NOTS"; then
  pass "tailscale absent: no informational note and no warn from this check"
else
  fail "tailscale absent: the check printed a note or a warn without a CLI"
fi
if [[ "$RC_NOTS" == "$RC_NOTS_BASE" \
      && "$(count_of "$OUT_NOTS" 'warning(s)')" == "$(count_of "$WORK/out.nots-base" 'warning(s)')" \
      && "$(count_of "$OUT_NOTS" 'failure(s)')" == "$(count_of "$WORK/out.nots-base" 'failure(s)')" ]]; then
  pass "tailscale absent: counts and exit code equal the check-free baseline (${RC_NOTS_BASE})"
else
  fail "tailscale absent: the check moved counts or the exit code off the baseline"
fi

# --- (d) the fixture's nameserver never reaches the report -----------------
# Header match only. Every run is checked, so a future change that printed the
# file or echoed a nameserver line would fail here.
LEAK=0
for f in "$WORK"/out.*; do
  if grep -qF "$FIXTURE_NS_ADDR" "$f"; then
    fail "the fixture nameserver literal appears in the report ($(basename "$f"))"
    LEAK=1
  fi
done
if (( ! LEAK )); then
  pass "no fixture nameserver value appears in any report (header match only)"
fi
if ! grep -qF 'search example-tailnet.ts.net lan' "$OUT_EXPECTED"; then
  pass "the fixture's search line never reaches the report either"
else
  fail "the fixture's search line was printed"
fi

echo "---"
if (( FAILURES != 0 )); then
  echo "FAILURES: ${FAILURES}" >&2
  exit 1
fi
echo "All resolv.conf ownership assertions passed (${PASS})."
exit 0
